import {spawnSync} from 'node:child_process';
import {cp,mkdir,readFile,writeFile,rm} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const website=fileURLToPath(new URL('../',import.meta.url));
const app=path.resolve(website,'../zuri-app-prototype');
const canonical=await readFile(path.join(website,'packages/intent-engine/index.mjs'),'utf8');
const installed=await readFile(path.join(app,'node_modules/@zuri/intent-engine/index.mjs'),'utf8');
if(canonical!==installed)throw new Error('The app intent engine is stale. Repack the canonical intent-engine package and reinstall its local vendor tarball before rebuilding.');
const result=spawnSync(process.execPath,['node_modules/vite/bin/vite.js','build','--config','vite.website.config.ts','--mode','website'],{cwd:app,stdio:'inherit'});
if(result.status!==0)process.exit(result.status??1);
const target=path.join(website,'public/zuri-app');
// This directory is generated by this script. Remove obsolete hashed bundles
// only after Vite succeeds, so old demo code is not shipped beside the live app.
if(path.relative(website,target)!==path.join('public','zuri-app'))throw new Error('Unexpected app output path.');
await rm(target,{recursive:true,force:true});
await mkdir(target,{recursive:true});
await cp(path.join(app,'dist-website'),target,{recursive:true});
const manifest=JSON.parse(await readFile(path.join(target,'manifest.webmanifest'),'utf8'));
manifest.start_url='./index.html#/lounge';
await writeFile(path.join(target,'manifest.webmanifest'),JSON.stringify(manifest,null,2));
console.log('Current ZURI web app packaged into the website.');
