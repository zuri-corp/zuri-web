const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.ZURI_BROWSER_PATH ? { executablePath: process.env.ZURI_BROWSER_PATH } : {}) })
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
  const page = await context.newPage()
  page.setDefaultTimeout(12000)
  const errors = [], passed = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error' && /validateDOMNesting|cannot be a descendant|Each child/.test(message.text())) errors.push(message.text()) })
  const base = process.env.ZURI_PREVIEW_URL || 'http://zuri.test/'
  if (!process.env.ZURI_PREVIEW_URL) {
    await context.route('http://zuri.test/**', async route => {
      const pathname = decodeURIComponent(new URL(route.request().url()).pathname)
      const target = path.resolve('dist', pathname === '/' ? 'index.html' : '.' + pathname)
      if (!target.startsWith(path.resolve('dist') + path.sep)) return route.abort()
      const contentType = { '.html': 'text/html', '.js': 'application/javascript', '.css': 'text/css' }[path.extname(target)] || 'application/octet-stream'
      try { await route.fulfill({ body: fs.readFileSync(target), contentType }) } catch { await route.fulfill({ status: 404, body: 'Not found' }) }
    })
    await context.route(/^https:\/\//, route => route.abort())
  }
  const go = async hash => { await page.goto(base + hash, { waitUntil: 'domcontentloaded' }); await page.locator('.zuri-global-nav').waitFor() }
  const text = value => page.getByText(value, { exact: true }).filter({ visible: true }).first()
  const snapshot = () => page.evaluate(() => JSON.parse(localStorage.getItem('zuri.prototype.v1')))
  fs.mkdirSync('verification', { recursive: true })
  try {
    await go('#/')
    await page.getByRole('button', { name: 'About Viola' }).click()
    await page.getByRole('dialog').waitFor()
    await page.getByRole('button', { name: 'Got it' }).click()
    passed.push('Zuri home and honest Viola placeholder')
    await go('#/motion/events_list')
    await page.getByRole('button', { name: 'Create event', exact: true }).click()
    await page.getByPlaceholder('e.g. Jinja Night Live').fill('Opportunity Open Day')
    await page.getByPlaceholder('Sat 20 Sep').fill('2026-11-01')
    await page.getByPlaceholder('Ticket price in UGX, e.g. 50000').fill('25000')
    await page.getByRole('button', { name: 'Create Event', exact: true }).click()
    await page.getByRole('button').filter({ hasText: 'Opportunity Open Day' }).first().click()
    let state = await snapshot()
    const event = state.events.find(event => event.name === 'Opportunity Open Day')
    assert.ok(event)
    await go('#/motion/ticket_select?eventId=' + event.id)
    await page.getByRole('button', { name: 'CONTINUE', exact: true }).click()
    await page.getByRole('button', { name: 'CONFIRM PURCHASE', exact: true }).click()
    await text('\u2713 ATTENDING').waitFor()
    state = await snapshot()
    assert.equal(state.walletBalance, 315000)
    assert.ok(state.purchasedTickets.includes(event.id))
    await page.reload()
    await page.getByRole('button', { name: 'TICKET ALREADY OWNED', exact: true }).waitFor()
    assert.equal((await snapshot()).walletTxs.length, 5)
    passed.push('New event checkout, receipt, persisted entitlement and duplicate prevention')
    await go('#/motion/ticket_confirm?eventId=e3&ticketType=camping&price=380000')
    assert.ok(await page.getByRole('button', { name: 'INSUFFICIENT BALANCE OR INVALID TICKET', exact: true }).isDisabled())
    assert.equal((await snapshot()).walletBalance, 315000)
    await go('#/motion/my_tickets')
    await page.getByRole('button').filter({ hasText: 'Opportunity Open Day' }).click()
    passed.push('Insufficient funds blocked and My Tickets opens saved event')
    await go('#/rizz/create')
    await page.getByRole('button', { name: /post A text update/i }).click()
    const caption = 'Available to collaborate on local opportunities.'
    await page.getByPlaceholder('Write a caption...').fill(caption)
    await page.getByRole('button', { name: /add context/i }).click()
    await page.getByRole('button', { name: /Project$/ }).last().click()
    await page.getByRole('button', { name: 'Nile Nights', exact: true }).click()
    await page.getByRole('button', { name: 'Done', exact: true }).click()
    await page.getByRole('button', { name: 'POST', exact: true }).click()
    await text('POSTED').waitFor()
    const post = (await snapshot()).contentItems.find(post => post.caption === caption)
    assert.ok(post)
    await go('#/xp/project_detail?projectId=p1')
    await page.getByRole('button', { name: 'media', exact: true }).click()
    await text(caption).waitFor()
    await go('#/rizz/discover')
    await page.getByPlaceholder('People, creators, spaces, content...').fill('Available to collaborate')
    await page.getByRole('button', { name: caption, exact: true }).click()
    await text(caption).waitFor()
    await page.getByRole('button', { name: /Nile Nights/ }).click()
    assert.match(page.url(), /xp\/project_detail/)
    await page.getByRole('button', { name: 'Go back', exact: true }).click()
    await page.waitForURL(/rizz\/reels/)
    passed.push('Publish, shared project content, Rizz discovery and cross-app Back')
    for (const hash of ['#/motion/event_detail?eventId=missing', '#/aura/space_detail?spaceId=missing', '#/xp/project_detail?projectId=missing', '#/rizz/creator?userId=missing']) {
      await go(hash)
      await page.getByText(/unavailable/i).filter({ visible: true }).first().waitFor()
    }
    passed.push('Missing records recover safely in all four modules')
    await go('#/aura/wallet')
    await page.getByText(/Demo wallet/).filter({ visible: true }).waitFor()
    assert.ok(await page.getByRole('button', { name: 'TOP UP', exact: true }).isDisabled())
    await go('#/aura/society_detail?societyId=soc3')
    await page.getByRole('button', { name: 'REQUEST TO JOIN', exact: true }).click()
    await page.getByText(/This Society is private/).filter({ visible: true }).waitFor()
    assert.equal((await snapshot()).societyMemberships.soc3, 'requested')
    passed.push('Wallet clearly marked demo and private requests do not grant access')
    await go('#/aura/owner_dashboard?spaceId=s4')
    await page.getByRole('button', { name: 'offerings', exact: true }).click()
    await page.getByRole('button', { name: '+ Add', exact: true }).first().click()
    await page.getByPlaceholder('e.g. Sunset Cruise').fill('Founders Workshop')
    await page.getByPlaceholder('e.g. 50', { exact: true }).fill('30000')
    await page.getByRole('button', { name: 'Add Offering', exact: true }).click()
    state = await snapshot()
    assert.ok(state.spaces.find(space => space.id === 's4').businessCategories.flatMap(category => category.offerings).some(offering => offering.name === 'Founders Workshop'))
    await go('#/aura/space_business?spaceId=s4')
    await text('Founders Workshop').waitFor()
    passed.push('Owner offering creation persists and updates customer catalog')
    const routes = ['#/aura/home', '#/aura/pings_list', '#/aura/ping_detail?pingId=ping1', '#/aura/space_detail?spaceId=s1', '#/aura/societies', '#/aura/society_detail?societyId=soc1', '#/aura/topic_chat?topicId=t1', '#/aura/spaces', '#/aura/find', '#/aura/find_category?category=stay', '#/aura/product_detail?productId=pr1', '#/aura/search', '#/motion/home', '#/motion/trips', '#/motion/hosted_space?eventId=e1', '#/motion/memories?eventId=e1', '#/motion/chat', '#/motion/search', '#/rizz/home', '#/rizz/music', '#/rizz/chat', '#/rizz/creator?userId=u1', '#/rizz/encounter', '#/xp/home', '#/xp/discover', '#/xp/projects', '#/xp/chat', '#/xp/creator_detail?userId=me']
    for (const hash of routes) {
      await go(hash)
      assert.equal(await text('This screen could not open').count(), 0, hash)
    }
    passed.push('28 additional screen routes render without runtime errors')
    await go('#/')
    await page.screenshot({ path: 'verification/zuri-home.png', fullPage: true })
    await go('#/aura/wallet')
    await page.screenshot({ path: 'verification/zuri-wallet.png', fullPage: true })
    assert.deepEqual(errors, [])
    fs.writeFileSync('verification/browser-results.json', JSON.stringify({ passed, errors, externalAssets: 'Blocked during isolated tests' }, null, 2))
    console.log(JSON.stringify({ passed, errors }, null, 2))
  } catch (error) {
    await page.screenshot({ path: 'verification/browser-failure.png' }).catch(() => {})
    fs.writeFileSync('verification/browser-failure.txt', (await page.locator('body').innerText()) + '\nERRORS: ' + JSON.stringify(errors))
    throw error
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
